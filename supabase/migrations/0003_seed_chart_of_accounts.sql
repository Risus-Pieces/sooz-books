-- ---------------------------------------------------------------------------
-- Guard rails: fail the migration rather than leave a broken chart behind.
-- ---------------------------------------------------------------------------
do $$
declare n int;
begin
  select count(*) into n from accounts a
   where a.parent_id is not null
     and not exists (select 1 from accounts p where p.id = a.parent_id);
  if n > 0 then
    raise exception 'chart of accounts has % orphaned parent links', n;
  end if;

  select count(*) into n from accounts a
    join accounts p on p.id = a.parent_id
   where p.type <> a.type;
  if n > 0 then
    raise exception 'chart of accounts has % accounts whose parent is a different type', n;
  end if;

  select count(*) into n from accounts where code in ('1200', '2000') and not is_control;
  if n > 0 then
    raise exception 'AR and AP must be control accounts';
  end if;
end $$;

