/**
 * Deduplication keys.
 *
 * Users re-import overlapping ranges constantly — with Relay it is the normal
 * case, because a `(Partial)` month is downloaded again as a complete month. Two
 * layers guard it:
 *
 *   0. `fileHash` — sha256 of the raw bytes. Catches the identical file twice.
 *   1. `rowFingerprint` — the per-row key stored on `bank_transactions.fingerprint`,
 *      behind a unique index on `(bank_account_id, fingerprint)`.
 *
 * `rowFingerprint` must be byte-identical to the Postgres function
 * `bank_txn_fingerprint(uuid, date, bigint, text, text, int)`. The database owns
 * that definition; this file is a faithful copy so the importer can compute keys
 * without a round trip, and `fingerprint.test.ts` asserts the two agree over a
 * table of cases — including vectors generated by psql itself.
 */

import { createHash } from 'node:crypto';

import type { CalendarDate } from '@/lib/dates';

import { normalizeDescription } from './normalize';

/** sha256 of the raw file bytes, lower-case hex. The file-level dedup key. */
export function fileHash(bytes: Uint8Array | ArrayBuffer): string {
  const view = bytes instanceof ArrayBuffer ? new Uint8Array(bytes) : bytes;
  return createHash('sha256').update(view).digest('hex');
}

export interface RowFingerprintInput {
  /** The `bank_accounts.id` uuid. Case-insensitive; Postgres renders uuids lower-case. */
  bankAccountId: string;
  date: CalendarDate;
  /** Integer cents, signed in company terms. */
  amountCents: number;
  description: string | null | undefined;
  /** A stable bank-provided id. When present it short-circuits the hash entirely. */
  externalId?: string | null;
  /** 0-based index among rows identical in (date, amount, normalised description). */
  occurrence: number;
}

/**
 * The per-row deduplication key.
 *
 * When the bank gives a stable id, the key is `x:<id>` — exact, immune to a
 * restated description, and needing no occurrence handling. Relay has no such
 * column, so the fallback is
 *
 * ```
 * sha256(bank_account_id | date | amount_cents | normalize_description(description) | occurrence)
 * ```
 *
 * Note what is deliberately absent: the running balance (it changes whenever a
 * later transaction is added), the category (banks recategorise retroactively),
 * the filename and the row index. Any of those would make a re-import of the same
 * transaction look new.
 */
export function rowFingerprint(input: RowFingerprintInput): string {
  const { externalId } = input;
  if (externalId !== null && externalId !== undefined && externalId !== '') {
    return `x:${externalId}`;
  }

  if (!Number.isSafeInteger(input.amountCents)) {
    throw new Error(
      `rowFingerprint: amountCents must be a whole number of cents; received ${input.amountCents}.`,
    );
  }
  if (!Number.isInteger(input.occurrence) || input.occurrence < 0) {
    throw new Error(
      `rowFingerprint: occurrence must be a non-negative integer; received ${input.occurrence}.`,
    );
  }

  const key = [
    // `uuid::text` in Postgres always renders lower-case.
    input.bankAccountId.toLowerCase(),
    // `date::text` under the default ISO DateStyle is exactly `YYYY-MM-DD`.
    input.date,
    // `bigint::text` is a plain integer, with a leading `-` when negative.
    String(input.amountCents),
    normalizeDescription(input.description),
    String(input.occurrence),
  ].join('|');

  return createHash('sha256').update(key, 'utf8').digest('hex');
}

/** The fields that decide whether two rows are indistinguishable. */
export interface OccurrenceInput {
  date: CalendarDate | '';
  amountCents: number;
  description: string | null | undefined;
}

/**
 * Assigns each row a deterministic occurrence index within its group of rows that
 * are identical in (date, amount, normalised description). Returns an array
 * parallel to the input.
 *
 * Two $8.19 Target charges on 1/28/2026 are a real event in this company's books,
 * and no natural key tells them apart. Numbering them 0 and 1 lets both exist and
 * lets a re-import recognise both.
 *
 * **Pass the rows in ascending chronological order.** Relay exports newest-first,
 * and a `(Partial)` month is a *suffix* of the eventual full month in that
 * direction — so numbering in file order would give the same transaction different
 * indices in the two files and duplicate it. Reversed to oldest-first, the partial
 * is a prefix of the full month and the indices agree.
 * `validateBalanceChain().ordered` produces exactly that order.
 */
export function assignOccurrences(rows: readonly OccurrenceInput[]): number[] {
  const seen = new Map<string, number>();
  return rows.map((row) => {
    const key = `${row.date}|${row.amountCents}|${normalizeDescription(row.description)}`;
    const next = seen.get(key) ?? 0;
    seen.set(key, next + 1);
    return next;
  });
}
