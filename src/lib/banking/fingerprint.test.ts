describe('fileHash', () => {
  it('is the sha256 of the raw bytes, lower-case hex', () => {
    const bytes = Buffer.from('Date,Payee,Amount\n2026-01-30,DAVESHOTCHICKEN,-97.43\n', 'utf8');
    expect(fileHash(bytes)).toBe(createHash('sha256').update(bytes).digest('hex'));
    expect(fileHash(bytes)).toMatch(/^[0-9a-f]{64}$/);
  });

  it('changes when a single byte changes', () => {
    expect(fileHash(Buffer.from('-97.43'))).not.toBe(fileHash(Buffer.from('-97.44')));
  });

  it('is what readFile reports as the file hash', async () => {
    const file = await readRelay('Relay 2026-01-01 #9726.csv');
    expect(file.sha256).toMatch(/^[0-9a-f]{64}$/);
  });
});

describe('rowFingerprint', () => {
  it('reproduces the frozen vectors taken from bank_txn_fingerprint()', () => {
    for (const { expected, ...input } of GOLDEN) {
      expect(rowFingerprint(input), `${input.date} ${input.description} #${input.occurrence}`).toBe(expected);
    }
  });

  it('short-circuits to x:<id> whenever the bank supplies a stable id', () => {
    const base = { bankAccountId: ACCOUNT_9726, date: '2026-03-01', amountCents: 100, occurrence: 0 };
    // Everything else about the row may change; the id alone decides.
    expect(rowFingerprint({ ...base, description: 'one', externalId: 'ABC123' })).toBe('x:ABC123');
    expect(rowFingerprint({ ...base, description: 'quite different', externalId: 'ABC123' })).toBe('x:ABC123');
  });

  it('separates the occurrence index, the amount, the date and the account', () => {
    const base = {
      bankAccountId: ACCOUNT_9726,
      date: '2026-01-28',
      amountCents: -819,
      description: 'Target',
      occurrence: 0,
    };
    const keys = new Set([
      rowFingerprint(base),
      rowFingerprint({ ...base, occurrence: 1 }),
      rowFingerprint({ ...base, amountCents: -820 }),
      rowFingerprint({ ...base, date: '2026-01-29' }),
      rowFingerprint({ ...base, bankAccountId: ACCOUNT_9973 }),
    ]);
    expect(keys.size).toBe(5);
  });

  it('is insensitive to case and punctuation in the description, as the database is', () => {
    const base = { bankAccountId: ACCOUNT_9726, date: '2026-02-15', amountCents: -5331, occurrence: 0 };
    expect(rowFingerprint({ ...base, description: 'Meta Store' })).toBe(
      rowFingerprint({ ...base, description: 'META  STORE!' }),
    );
  });

  it('accepts an upper-case uuid, because Postgres renders one lower-case', () => {
    const base = { date: '2026-01-30', amountCents: -9743, description: 'DAVESHOTCHICKEN', occurrence: 0 };
    expect(rowFingerprint({ ...base, bankAccountId: ACCOUNT_9726.toUpperCase() })).toBe(
      rowFingerprint({ ...base, bankAccountId: ACCOUNT_9726 }),
    );
  });

  it('refuses a fractional amount rather than hashing one', () => {
    expect(() =>
      rowFingerprint({
        bankAccountId: ACCOUNT_9726,
        date: '2026-01-30',
        amountCents: -97.43,
        description: 'DAVESHOTCHICKEN',
        occurrence: 0,
      }),
    ).toThrow(/whole number of cents/);
  });
});

describe('rowFingerprint matches the Postgres function it has to agree with', () => {
  const sql = parityClient();
  afterAll(async () => {
    await sql.end({ timeout: 5 });
  });

  it('agrees on the frozen vectors and on every real Relay transaction', async () => {
    const cases: RowFingerprintInput[] = GOLDEN.map((golden) => ({
      bankAccountId: golden.bankAccountId,
      date: golden.date,
      amountCents: golden.amountCents,
      description: golden.description,
      externalId: golden.externalId,
      occurrence: golden.occurrence,
    }));

    // Plus every transaction in the real January and September statements, keyed
    // to the bank account those files actually belong to.
    for (const [filename, account] of [
      ['Relay 2026-01-01 #9726.csv', ACCOUNT_9726],
      ['Relay 2026-02-01 #9726.csv', ACCOUNT_9726],
      ['Relay (Partial) 2026-09-01 #9726.csv', ACCOUNT_9726],
      ['Relay 2026-01-01 #9973.csv', ACCOUNT_9973],
    ] as const) {
      const parsed = applyProfile(await readRelay(filename), RELAY_PROFILE);
      const ordered = validateBalanceChain(parsed.rows).ordered.filter((row) => row.usable);
      const occurrences = assignOccurrences(ordered);
      ordered.forEach((row, index) => {
        cases.push({
          bankAccountId: account,
          date: row.date as string,
          amountCents: row.amountCents,
          description: row.description,
          externalId: row.externalId,
          occurrence: occurrences[index],
        });
      });
    }

    expect(cases.length).toBeGreaterThan(60);

    // Six parallel text arrays, bound as parameters and cast on the server. The
    // database does the uuid, date and bigint casts itself, so the comparison is
    // against exactly the types `bank_txn_fingerprint` is declared with.
    const rows = await sql<Array<{ i: number; expected: string }>>`
      select
        (ordinality - 1)::int as i,
        bank_txn_fingerprint(
          account::uuid, txn_date::date, amount::bigint, description, external_id, occurrence::int
        ) as expected
      from unnest(
        ${cases.map((c) => c.bankAccountId)}::text[],
        ${cases.map((c) => c.date)}::text[],
        ${cases.map((c) => String(c.amountCents))}::text[],
        ${cases.map((c) => c.description ?? null)}::text[],
        ${cases.map((c) => c.externalId ?? null)}::text[],
        ${cases.map((c) => String(c.occurrence))}::text[]
      ) with ordinality as t(account, txn_date, amount, description, external_id, occurrence, ordinality)
    `;

    expect(rows.length).toBe(cases.length);
    const drift = rows
      .filter((row) => rowFingerprint(cases[row.i]) !== row.expected)
      .map((row) => ({ input: cases[row.i], postgres: row.expected, typescript: rowFingerprint(cases[row.i]) }));
    expect(drift).toEqual([]);
  });
});

describe('assignOccurrences', () => {
  it('numbers rows that are identical in date, amount and normalized description', () => {
    const rows = [
      { date: '2026-01-28', amountCents: -819, description: 'Target' },
      { date: '2026-01-28', amountCents: -1338, description: 'Target' },
      { date: '2026-01-28', amountCents: -819, description: 'Target' },
    ];
    expect(assignOccurrences(rows)).toEqual([0, 0, 1]);
  });

  it('groups on the normalized description, so a restated payee does not split a pair', () => {
    expect(
      assignOccurrences([
        { date: '2026-02-15', amountCents: -5331, description: 'Meta Store' },
        { date: '2026-02-15', amountCents: -5331, description: 'META  STORE' },
      ]),
    ).toEqual([0, 1]);
  });

  it('gives the two real same-day Target charges different indices', async () => {
    const parsed = applyProfile(await readRelay('Relay 2026-01-01 #9726.csv'), RELAY_PROFILE);
    const ordered = validateBalanceChain(parsed.rows).ordered;
    const occurrences = assignOccurrences(ordered);

    const targets = ordered
      .map((row, index) => ({ row, occurrence: occurrences[index] }))
      .filter((entry) => entry.row.description === 'Target');

    expect(targets.map((t) => t.row.amountCents)).toEqual([-1338, -819]);
    // Different amounts, so both are occurrence 0 — the index only has to work
    // when nothing else tells two rows apart.
    expect(targets.map((t) => t.occurrence)).toEqual([0, 0]);

    // Every fingerprint in the file is distinct, which is what the unique index
    // on (bank_account_id, fingerprint) requires.
    const fingerprints = ordered.map((row, index) =>
      rowFingerprint({
        bankAccountId: ACCOUNT_9726,
        date: row.date as string,
        amountCents: row.amountCents,
        description: row.description,
        occurrence: occurrences[index],
      }),
    );
    expect(new Set(fingerprints).size).toBe(fingerprints.length);
  });

  it('reproduces the same indices when a partial month is re-imported as a full one', () => {
    // Oldest-first, which is the order `validateBalanceChain` produces. A Relay
    // `(Partial)` file is a prefix of the eventual full month in this direction,
    // so the overlapping rows must keep their indices.
    const full = [
      { date: '2026-02-02', amountCents: -1499, description: 'Amazon' },
      { date: '2026-02-02', amountCents: -1795, description: 'Amazon' },
      { date: '2026-02-02', amountCents: -5226, description: 'Amazon' },
      { date: '2026-02-03', amountCents: -1499, description: 'Amazon' },
      { date: '2026-02-03', amountCents: -1499, description: 'Amazon' },
      { date: '2026-02-04', amountCents: -1699, description: 'Amazon' },
    ];
    const partial = full.slice(0, 4);

    const fullIndices = assignOccurrences(full);
    const partialIndices = assignOccurrences(partial);

    expect(partialIndices).toEqual(fullIndices.slice(0, partial.length));
    // And the genuinely duplicated 2026-02-03 pair is numbered 0 then 1.
    expect(fullIndices).toEqual([0, 0, 0, 0, 1, 0]);
  });

  it('returns an empty array for no rows', () => {
    expect(assignOccurrences([])).toEqual([]);
  });
});
